// French sets a space before ; : ? ! and inside « », and a line must never
// break at that space. The text above is written with ordinary spaces so it
// stays readable; this puts in the non-breaking ones.
const NBSP = ' ';
const NARROW_NBSP = ' ';

function typeset(value: string): string {
  return value
    .replace(/ ([;?!])/g, `${NARROW_NBSP}$1`)
    .replace(/ :/g, `${NBSP}:`)
    .replace(/« /g, `«${NBSP}`)
    .replace(/ »/g, `${NBSP}»`)
    .replace(/(\d) (\d{3})(?!\d)/g, `$1${NARROW_NBSP}$2`)
    .replace(/(\d) ([$%]|Mo\b)/g, `$1${NBSP}$2`);
}

